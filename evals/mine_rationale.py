"""Mine candidate "why" questions from places where maintainers state reasons in their own words.

    REPO_ASSIST_DATA_DIR=data-v2 python evals/mine_rationale.py got httpx chi

Sources, strongest first: release-note "Why:" lines, PR descriptions, commit message
bodies and documentation sentences that use causal language ("because", "so that",
"the reason"). Output goes to evals/candidates/<repo>.jsonl for manual review: a
candidate becomes a test question only after a person checks that the excerpt really
states a reason and writes the question and key facts from it. Nothing here is
generated by an LLM, so it costs no quota and can't invent a rationale.
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from evals.common import EVAL_DIR  # noqa: E402
from repo_assist import store  # noqa: E402

CAUSAL = re.compile(r"\b(because|so that|in order to|the reason|reasons? (?:is|are|why)|motivat\w+|"
                    r"we decided|instead of|rather than|this (?:means|allows|avoids|prevents))\b", re.IGNORECASE)
WHY_LINE = re.compile(r"^\s*[-*]?\s*(?:\*\*)?Why:?(?:\*\*)?:?\s*(.+)$", re.IGNORECASE | re.MULTILINE)
SENTENCE = re.compile(r"[^.!?\n]*\b(?:because|so that|in order to|the reason)\b[^.!?\n]*[.!?]", re.IGNORECASE)
PER_SOURCE_LIMIT = 40


def release_why_lines(conn, repo_id: str) -> list[dict]:
    out = []
    for row in conn.execute("SELECT ref, title, text, created_at FROM chunks WHERE repo_id = ? AND kind = 'release'",
                            (repo_id,)):
        lines = row["text"].splitlines()
        for i, line in enumerate(lines):
            match = WHY_LINE.match(line)
            if match:
                change = next((lines[j].strip() for j in range(i - 1, max(i - 6, -1), -1)
                               if lines[j].strip().startswith(("-", "*")) and "Why" not in lines[j]), "")
                out.append({"source": "release_why", "ref": row["ref"], "date": row["created_at"][:10],
                            "change": change, "rationale": match.group(1).strip()})
    return out


def causal_excerpts(conn, repo_id: str, kinds: tuple[str, ...], source: str) -> list[dict]:
    rows = conn.execute(
        f"SELECT ref, kind, title, text, created_at FROM chunks WHERE repo_id = ? AND kind IN "
        f"({','.join('?' * len(kinds))})", (repo_id, *kinds)).fetchall()
    scored = []
    for row in rows:
        body = row["text"][:3000] if row["kind"] != "doc" else row["text"]
        sentences = [s.strip() for s in SENTENCE.findall(body)]
        if not sentences:
            continue
        density = len(CAUSAL.findall(body)) / max(1, len(body) / 1000)
        scored.append((density, {"source": source, "ref": row["ref"], "date": (row["created_at"] or "")[:10],
                                 "title": row["title"], "rationale": " ... ".join(sentences[:3])}))
    scored.sort(key=lambda item: -item[0])
    return [c for _, c in scored[:PER_SOURCE_LIMIT]]


def main(repo_ids: list[str]) -> None:
    out_dir = EVAL_DIR / "candidates"
    out_dir.mkdir(exist_ok=True)
    with store.session() as conn:
        for repo_id in repo_ids:
            candidates = (release_why_lines(conn, repo_id)
                          + causal_excerpts(conn, repo_id, ("pr",), "pr_description")
                          + causal_excerpts(conn, repo_id, ("commit",), "commit_message")
                          + causal_excerpts(conn, repo_id, ("doc",), "documentation"))
            path = out_dir / f"{repo_id}.jsonl"
            path.write_text("".join(json.dumps(c) + "\n" for c in candidates))
            by_source = {}
            for c in candidates:
                by_source[c["source"]] = by_source.get(c["source"], 0) + 1
            print(f"{repo_id}: {len(candidates)} candidates {by_source} -> {path}")


if __name__ == "__main__":
    main(sys.argv[1:])
